"""Synthetic TOY dataset. NOT patent data.

It exists so the whole pipeline (build -> queries -> predict -> backtest) can be run
and tested without downloading ~10 GB. Fields are called TOY001.. and the process
that generates combinations is *planted* (triadic closure + clusters; or no structure at all, as a placebo), so a good
predictor should beat chance on it. That proves the machinery works; it is not
evidence that the method works on real technology history.
"""
from __future__ import annotations

import csv
import json
import random
from pathlib import Path


def generate(out_dir, n_fields: int = 150, seed: int = 7, y0: int = 1976, y1: int = 2024,
             structure: str = "strong") -> dict:
    """structure: "strong" plants triadic closure + clusters; "none" combines pairs at random
    (a placebo: a sound backtest must find no skill there)."""
    if structure not in ("strong", "none"):
        raise ValueError("structure must be 'strong' or 'none'")
    rng = random.Random(seed)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)

    n_clusters = 6
    n_initial = 30
    codes = [f"TOY{i:03d}" for i in range(n_fields)]
    cluster = {c: rng.randrange(n_clusters) for c in codes}
    birth = {}
    for i, c in enumerate(codes):
        if i < n_initial:
            birth[c] = y0
        else:  # the rest appear gradually through 2005
            birth[c] = y0 + 1 + int((i - n_initial) * (2005 - y0 - 1) / (n_fields - n_initial))

    # builds_on: each later field builds on 3-6 earlier ones, preferring its own cluster
    builds = []
    for c in codes[n_initial:]:
        earlier = [d for d in codes if birth[d] < birth[c]]
        same = [d for d in earlier if cluster[d] == cluster[c]]
        k = rng.randint(3, 6)
        chosen = set()
        while len(chosen) < min(k, len(earlier)):
            pool = same if (same and rng.random() < 0.7) else earlier
            chosen.add(rng.choice(pool))
        for d in sorted(chosen):  # sets of strings iterate in hash-seed order; sort so the toy data is reproducible
            builds.append((c, d, rng.randint(5, 80), min(2024, birth[c] + rng.randint(0, 3))))

    # combined_with: planted triadic closure
    adj = {c: set() for c in codes}
    combined = []
    for year in range(y0, y1 + 1):
        alive = [c for c in codes if birth[c] <= year]
        for i, a in enumerate(alive):
            for b in alive[i + 1:]:
                if b in adj[a]:
                    continue
                cn = len(adj[a] & adj[b])
                if structure == "strong":
                    p = 0.0004 * (1 + cn) ** 2.5 * (8.0 if cluster[a] == cluster[b] else 0.3)
                else:
                    p = 0.0008
                if rng.random() < min(p, 0.6):
                    adj[a].add(b)
                    adj[b].add(a)
                    combined.append((a, b, rng.randint(3, 40), year))

    with open(out / "fields.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["code", "title", "first_year", "n_patents"])
        for c in codes:
            w.writerow([c, f"Synthetic field {c[3:]} (cluster {cluster[c]})", birth[c], rng.randint(50, 5000)])
    with open(out / "builds_on.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["src", "dst", "count", "first_year"])
        w.writerows(builds)
    with open(out / "combined_with.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["a", "b", "count", "first_year"])
        w.writerows((min(a, b), max(a, b), n, y) for a, b, n, y in combined)
    (out / "README.txt").write_text(
        "SYNTHETIC TOY DATA - generated by techtree.toy. Not patent data. "
        "Used only to exercise and test the pipeline.\n"
    )
    stats = {"fields": len(codes), "builds_links": len(builds), "combined_pairs": len(combined)}
    (out / "meta.json").write_text(
        json.dumps({"source": "toy", "structure": structure, "data_end_year": y1, "min_year": y0,
                    "slice": "toy", **stats}, indent=2)
    )
    return stats
